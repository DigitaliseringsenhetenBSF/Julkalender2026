import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { CONTENT_DIR } from './paths.ts';

/**
 * Campaign content and rules from `content/*.json` (SPEC §5). Validated on load so a typo in a
 * content file stops the server instead of producing a subtly wrong calendar.
 */

const isoDate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'expected YYYY-MM-DD');

const campaignSchema = z.object({
  timezone: z.string().min(1),
  firstMissionDate: isoDate,
  totalMissions: z.number().int().positive(),
  lastTickOffDate: isoDate,
  completionsPerPiece: z.number().int().positive(),
});

const missionsSchema = z.object({
  missions: z.array(
    z.object({
      day: z.number().int().positive(),
      title: z.string().min(1),
      /** "Gör så här" */
      howTo: z.string().min(1),
      /** "Om du vill" */
      ifYouWant: z.string(),
      /** Plain file name in assets/icons. */
      icon: z.string().regex(/^[\w.-]+\.svg$/),
      /** The illustration the campaign owner described; kept for future artwork. */
      iconDescription: z.string().optional(),
    }),
  ),
});

/** content/puzzle.json – edited by people. */
const puzzleSchema = z.object({
  columns: z.number().int().positive(),
  rows: z.number().int().positive(),
  unlockSeed: z.number().int(),
  cutSeed: z.number().int(),
  /** How close (share of a cell) a piece must lie to its slot to count as placed. */
  correctTolerance: z.number().positive().max(0.5),
  source: z.string(),
  pieces: z.array(z.object({ id: z.number().int().positive(), alt: z.string().min(1) })),
});

/** content/puzzle-shapes.json – generated by `npm run puzzle:cut`. */
const shapesSchema = z.object({
  imageWidth: z.number().int().positive(),
  imageHeight: z.number().int().positive(),
  columns: z.number().int().positive(),
  rows: z.number().int().positive(),
  pad: z.object({ x: z.number().min(0), y: z.number().min(0) }),
  pieces: z.array(
    z.object({
      id: z.number().int().positive(),
      // Plain file names only – they are joined onto the pieces folder when served.
      file: z.string().regex(/^[\w.-]+\.webp$/),
      shape: z.string().startsWith('M'),
    }),
  ),
});

export type CampaignContent = z.infer<typeof campaignSchema>;
export type MissionContent = z.infer<typeof missionsSchema>['missions'][number];
export interface PuzzlePieceContent {
  id: number;
  alt: string;
  file: string;
  /** Outline in 0–1 units of the piece box, for an objectBoundingBox clip path. */
  shape: string;
}

export interface PuzzleContent {
  columns: number;
  rows: number;
  unlockSeed: number;
  correctTolerance: number;
  /** Width / height of the whole picture. */
  imageAspect: number;
  /** Share of a cell the piece box extends beyond the cell on each side (room for tabs). */
  pad: { x: number; y: number };
  pieces: PuzzlePieceContent[];
}

export interface Content {
  campaign: CampaignContent;
  missions: MissionContent[];
  puzzle: PuzzleContent;
}

function readJson(dir: string, file: string): unknown {
  return JSON.parse(readFileSync(join(dir, file), 'utf8'));
}

export function loadContent(dir: string = CONTENT_DIR): Content {
  const campaign = campaignSchema.parse(readJson(dir, 'campaign.json'));
  const { missions } = missionsSchema.parse(readJson(dir, 'missions.json'));
  const puzzleFile = puzzleSchema.parse(readJson(dir, 'puzzle.json'));
  const shapes = shapesSchema.parse(readJson(dir, 'puzzle-shapes.json'));
  if (shapes.columns !== puzzleFile.columns || shapes.rows !== puzzleFile.rows) {
    throw new Error('puzzle-shapes.json does not match puzzle.json – run `npm run puzzle:cut`');
  }
  const shapeById = new Map(shapes.pieces.map((p) => [p.id, p]));
  const puzzle: PuzzleContent = {
    columns: puzzleFile.columns,
    rows: puzzleFile.rows,
    unlockSeed: puzzleFile.unlockSeed,
    correctTolerance: puzzleFile.correctTolerance,
    imageAspect: shapes.imageWidth / shapes.imageHeight,
    pad: shapes.pad,
    pieces: puzzleFile.pieces.map((p) => {
      const shape = shapeById.get(p.id);
      if (!shape) throw new Error(`No cut shape for piece ${p.id} – run \`npm run puzzle:cut\``);
      return { id: p.id, alt: p.alt, file: shape.file, shape: shape.shape };
    }),
  };

  const days = missions.map((m) => m.day).sort((a, b) => a - b);
  const expectedDays = Array.from({ length: campaign.totalMissions }, (_, i) => i + 1);
  if (days.join() !== expectedDays.join()) {
    throw new Error(`missions.json must contain days 1–${campaign.totalMissions} exactly once`);
  }

  const ids = puzzle.pieces.map((p) => p.id).sort((a, b) => a - b);
  const expectedIds = Array.from({ length: puzzle.columns * puzzle.rows }, (_, i) => i + 1);
  if (ids.join() !== expectedIds.join()) {
    throw new Error(`puzzle.json must contain piece ids 1–${expectedIds.length} exactly once`);
  }

  if (campaign.lastTickOffDate < campaign.firstMissionDate) {
    throw new Error('lastTickOffDate must not be before firstMissionDate');
  }

  return { campaign, missions, puzzle };
}
