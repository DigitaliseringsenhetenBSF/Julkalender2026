/**
 * Cuts the puzzle source image into classic jigsaw pieces (generated artefacts, SPEC §7).
 *   npm run puzzle:cut
 * Reads columns, rows, cutSeed and source from content/puzzle.json and writes:
 *   - assets/puzzle/pieces/bit-NN.webp  (transparent outside the piece outline)
 *   - content/puzzle-shapes.json        (outline per piece, for hit-testing in the UI)
 * Uses the Chromium that Playwright already installs, so no image library is needed.
 * Deterministic: the same seed gives the same shapes. Do not re-cut after launch.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from '@playwright/test';
import { CONTENT_DIR, PIECES_DIR, ROOT_DIR } from '../src/data/paths.ts';
import { cutJigsaw } from '../src/domain/jigsaw.ts';

/** Output size relative to the source image: cells of ~150 px look sharp on 2× screens. */
const OUTPUT_SCALE = 0.8;
const WEBP_QUALITY = 0.86;

const puzzle = JSON.parse(readFileSync(join(CONTENT_DIR, 'puzzle.json'), 'utf8')) as {
  columns: number;
  rows: number;
  cutSeed: number;
  source: string;
};
const sourcePath = join(ROOT_DIR, 'assets', 'puzzle', puzzle.source);
const png = readFileSync(sourcePath);
// PNG IHDR: width and height are big-endian uint32 at bytes 16 and 20.
const width = png.readUInt32BE(16);
const height = png.readUInt32BE(20);

const cut = cutJigsaw(width, height, puzzle.columns, puzzle.rows, puzzle.cutSeed);
console.log(
  `Cutting ${width}×${height} into ${puzzle.columns}×${puzzle.rows} = ${cut.pieces.length} pieces`,
);

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const images: string[] = await page.evaluate(
    async ({ dataUrl, pieces, scale, quality }) => {
      const image = new Image();
      image.src = dataUrl;
      await image.decode();
      return pieces.map((piece) => {
        const canvas = document.createElement('canvas');
        canvas.width = Math.round(piece.box.width * scale);
        canvas.height = Math.round(piece.box.height * scale);
        const ctx = canvas.getContext('2d');
        if (!ctx) throw new Error('no 2d context');
        ctx.scale(scale, scale);
        ctx.translate(-piece.box.left, -piece.box.top);
        const outline = new Path2D(piece.path);
        ctx.save();
        ctx.clip(outline);
        ctx.drawImage(image, 0, 0);
        // A soft bevel along the cut so pieces read as cardboard pieces.
        ctx.lineJoin = 'round';
        ctx.strokeStyle = 'rgba(0, 0, 0, 0.35)';
        ctx.lineWidth = 3 / scale;
        ctx.stroke(outline);
        ctx.strokeStyle = 'rgba(255, 255, 255, 0.35)';
        ctx.lineWidth = 1 / scale;
        ctx.stroke(outline);
        ctx.restore();
        return canvas.toDataURL('image/webp', quality);
      });
    },
    {
      dataUrl: `data:image/png;base64,${png.toString('base64')}`,
      pieces: cut.pieces.map((p) => ({ box: p.box, path: p.path })),
      scale: OUTPUT_SCALE,
      quality: WEBP_QUALITY,
    },
  );

  mkdirSync(PIECES_DIR, { recursive: true });
  for (const file of readdirSync(PIECES_DIR)) rmSync(join(PIECES_DIR, file));
  let bytes = 0;
  images.forEach((dataUrl, i) => {
    const data = Buffer.from(dataUrl.split(',')[1] ?? '', 'base64');
    bytes += data.length;
    writeFileSync(join(PIECES_DIR, pieceFile(i + 1)), data);
  });

  const shapes = {
    $comment: 'GENERATED by `npm run puzzle:cut` – do not edit by hand.',
    imageWidth: width,
    imageHeight: height,
    columns: puzzle.columns,
    rows: puzzle.rows,
    // The piece box extends this share of a cell beyond the cell on each side (for the tabs).
    pad: { x: cut.pad / cut.cellWidth, y: cut.pad / cut.cellHeight },
    pieces: cut.pieces.map((p) => ({ id: p.id, file: pieceFile(p.id), shape: p.shape })),
  };
  writeFileSync(join(CONTENT_DIR, 'puzzle-shapes.json'), `${JSON.stringify(shapes, null, 2)}\n`);
  console.log(
    `Wrote ${images.length} pieces (${Math.round(bytes / 1024)} kB) and content/puzzle-shapes.json`,
  );
} finally {
  await browser.close();
}

function pieceFile(id: number): string {
  return `bit-${String(id).padStart(2, '0')}.webp`;
}
